"""Preprocess NSCLC-Radiogenomics using TotalSegmentator lung masks.

The full CT field of view is resized to 256x256 and resampled to 2 mm through
plane spacing.  Lung labels are always generated by TotalSegmentator.
"""

from __future__ import annotations

import sys
from pathlib import Path

from tqdm.auto import tqdm

ROOT_DIR = Path(__file__).resolve().parents[1]
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from scripts.preprocess_nsclc import (
    TOTALSEGMENTATOR_FAST_TASK_ID,
    TOTALSEGMENTATOR_LUNG_TASK_ID,
    process_radiogenomics_case,
    sync_split_config,
    write_report,
)

RAW_ROOT = Path(r"D:\NSCLC-Radiogenomics")
DATASET_ROOT = ROOT_DIR / "data" / "nsclc_radiogenomics"
OLD_DATASET_ROOT = Path(r"D:\2.5D Lung Tumor Segmentation\data\nsclc_radiogenomics")
CASE_IDS: list[str] | None = None
HU_WINDOW_LOW = -700
HU_WINDOW_HIGH = 500
OUTPUT_Z_SPACING_MM = 2.0
TOTALSEGMENTATOR_DEVICE: str | None = "cuda"
LUNG_SEGMENTATION_MODE = "accurate"  # "fast" or "accurate"
LUNG_SEGMENTATION_SETTINGS = {
    "fast": {
        "task_id": TOTALSEGMENTATOR_FAST_TASK_ID,
        "trainer": "nnUNetTrainer_4000epochs_NoMirroring",
        "resample_mm": 3.0,
    },
    "accurate": {
        "task_id": TOTALSEGMENTATOR_LUNG_TASK_ID,
        "trainer": "nnUNetTrainerNoMirroring",
        "resample_mm": 1.5,
    },
}
TOTALSEGMENTATOR_LUNG_ROIS = (
    "lung_upper_lobe_left", "lung_lower_lobe_left", "lung_upper_lobe_right",
    "lung_middle_lobe_right", "lung_lower_lobe_right",
)
REUSE_EXISTING_LUNG_MASK = True
TUMOR_FILL_HOLES = True
TUMOR_KEEP_LARGEST_COMPONENT = False
TUMOR_MIN_COMPONENT_VOXELS = 100
OVERWRITE = False
DRY_RUN = False
SHOW_PROGRESS = True
STOP_ON_FAILURE = False


def main() -> int:
    if OUTPUT_Z_SPACING_MM <= 0:
        raise SystemExit("OUTPUT_Z_SPACING_MM must be positive")
    if LUNG_SEGMENTATION_MODE not in LUNG_SEGMENTATION_SETTINGS:
        raise SystemExit("LUNG_SEGMENTATION_MODE must be 'fast' or 'accurate'")
    lung_settings = LUNG_SEGMENTATION_SETTINGS[LUNG_SEGMENTATION_MODE]
    sync_split_config(OLD_DATASET_ROOT, DATASET_ROOT)
    cases = sorted(path for path in RAW_ROOT.glob("R*") if path.is_dir())
    requested = set(CASE_IDS or [])
    cases = [path for path in cases if not requested or path.name in requested]
    if requested and len(cases) != len(requested):
        raise SystemExit(
            f"requested cases not found: {', '.join(sorted(requested - {path.name for path in cases}))}"
        )
    rows: list[dict[str, str]] = []
    iterator = (
        tqdm(cases, desc="Preprocessing", unit="case", dynamic_ncols=True)
        if SHOW_PROGRESS
        else cases
    )
    for case_dir in iterator:
        try:
            row = process_radiogenomics_case(
                case_dir,
                DATASET_ROOT / "processed",
                DATASET_ROOT / "nifti",
                DATASET_ROOT / "intermediate" / "totalsegmentator",
                overwrite=OVERWRITE,
                dry_run=DRY_RUN,
                device=TOTALSEGMENTATOR_DEVICE,
                hu_low=HU_WINDOW_LOW,
                hu_high=HU_WINDOW_HIGH,
                output_z_spacing_mm=OUTPUT_Z_SPACING_MM,
                task_id=lung_settings["task_id"],
                trainer=lung_settings["trainer"],
                resample_mm=lung_settings["resample_mm"],
                lung_rois=TOTALSEGMENTATOR_LUNG_ROIS,
                reuse_existing_lung_mask=REUSE_EXISTING_LUNG_MASK,
                tumor_fill_holes=TUMOR_FILL_HOLES,
                tumor_keep_largest_component=TUMOR_KEEP_LARGEST_COMPONENT,
                tumor_min_component_voxels=TUMOR_MIN_COMPONENT_VOXELS,
            )
        except Exception as error:
            row = {
                "raw_case_id": case_dir.name,
                "case_id": case_dir.name,
                "status": "failed",
                "message": f"{type(error).__name__}: {error}",
            }
        rows.append(row)
        message = f"{row['status'].upper()}: {case_dir.name} {row.get('message', '')}"
        tqdm.write(message) if SHOW_PROGRESS else print(message)
        write_report(rows, DATASET_ROOT / "processing_report.csv")
        if row["status"] == "failed" and STOP_ON_FAILURE:
            return 1
    return 0 if all(row["status"] != "failed" for row in rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
